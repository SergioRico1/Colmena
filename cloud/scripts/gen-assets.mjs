// Writes cloud/src/assets.js: the app's text files a hosted workspace reads (prompts/ and its
// skills), bundled into the Worker and registered with server/bundled.mjs. Generated before
// every `wrangler dev` / `wrangler deploy` (npm run assets); never committed.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const files = {};
for (const folder of ["prompts", "prompts/skills"])
  for (const name of readdirSync(path.join(root, folder)).filter((n) => n.endsWith(".md")).sort())
    files[folder + "/" + name] = readFileSync(path.join(root, folder, name), "utf8");
const out = `// Generated by cloud/scripts/gen-assets.mjs. Do not edit.
import { bundleFiles } from "../../server/bundled.mjs";
bundleFiles(${JSON.stringify(files)});
`;
writeFileSync(path.join(root, "cloud", "src", "assets.js"), out);
console.log(`cloud/src/assets.js: ${Object.keys(files).length} files, ${Math.round(out.length / 1024)} KB`);
