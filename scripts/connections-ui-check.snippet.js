async (page) => {
  const origin = new URL(page.url()).origin;
  const state = await (await page.request.get(origin + '/fixture-state')).json();
  const read = state.approvals.find(a => a.kind === 'read').id;
  const send = state.approvals.find(a => a.kind === 'send').id;
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({width: 1440, height: 1080});
  await page.goto(origin + '/design-reference/09b/Connections.dc.html');
  await page.getByRole('heading', {name: 'Conexiones', exact: true}).waitFor();
  await page.evaluate(() => document.fonts.ready.then(() => true));
  await page.screenshot({path: 'output/playwright/connections-09b-original.png', fullPage: true});
  const reference = await page.getByRole('heading', {name: 'Conexiones', exact: true}).boundingBox();
  await page.goto(origin + '/connections/Connections.dc.html');
  await page.getByRole('button', {name: 'Desconectar', exact: true}).waitFor();
  await page.evaluate(() => document.fonts.ready.then(() => true));
  const actual = await page.getByRole('heading', {name: 'Conexiones', exact: true}).boundingBox();
  if (JSON.stringify(reference) !== JSON.stringify(actual)) throw Error('09b heading geometry changed');
  if (/Composio|Cambiar clave|Clave cifrada/.test(await page.locator('body').innerText())) throw Error('Internal configuration leaked');
  await page.screenshot({path: 'output/playwright/connections-09b-live.png', fullPage: true});
  await page.getByRole('textbox', {name: 'Buscar una app'}).fill('Calendar');
  await page.getByText('Calendario de prueba', {exact: true}).waitFor();
  await page.getByRole('button', {name: 'Correo y calendario', exact: true}).click();
  await page.goto(origin + '/connections/Permissions.dc.html?account=fixture-account');
  await page.getByRole('button', {name: 'Listo', exact: true}).waitFor();
  await page.getByRole('radio', {name: 'Trabajo', exact: true}).click();
  const input = page.getByRole('textbox');
  if ((await input.inputValue()) !== 'Gmail trabajo') throw Error('Preset selection not bound');
  await input.fill('Equipo de prueba');
  await page.screenshot({path: 'output/playwright/connections-09c-name.png', fullPage: true});
  await page.getByRole('button', {name: 'Listo', exact: true}).click();
  await page.getByText('Equipo de prueba', {exact: true}).waitFor();
  await page.goto(origin + '/connections/Permissions.dc.html?approval=' + encodeURIComponent(read));
  await page.getByRole('button', {name: 'Permitir', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Detalles técnicos', exact: true}).click();
  await page.getByText('GMAIL_FETCH_EMAILS', {exact: false}).waitFor();
  await page.getByRole('checkbox').click();
  if (await page.getByRole('checkbox').getAttribute('aria-checked') !== 'true') throw Error('Remember state failed');
  await page.screenshot({path: 'output/playwright/connections-09c-read.png', fullPage: true});
  await page.getByRole('button', {name: 'Permitir', exact: true}).click();
  await page.waitForURL('**/#/inbox');
  await page.goto(origin + '/connections/Permissions.dc.html?approval=' + encodeURIComponent(send));
  const hold = page.getByRole('button', {name: 'Mantén pulsado para enviar', exact: true});
  await hold.waitFor();
  await page.getByText('hotel@example.invalid', {exact: false}).waitFor();
  await page.screenshot({path: 'output/playwright/connections-09c-send.png', fullPage: true});
  const before = (await (await page.request.get(origin + '/fixture-state')).json()).calls.filter(c => c.op === 'commit').length;
  await hold.click();
  const after = (await (await page.request.get(origin + '/fixture-state')).json()).calls.filter(c => c.op === 'commit').length;
  if (before !== after) throw Error('Short click sent email');
  await hold.focus();
  await page.keyboard.down('Space');
  await page.waitForURL('**/#/inbox');
  await page.keyboard.up('Space');
  const final = await (await page.request.get(origin + '/fixture-state')).json();
  if (final.calls.filter(c => c.op === 'commit').length !== before + 1) throw Error('Hold must execute exactly once');
  await page.goto(origin + '/connections/Connections.dc.html');
  await page.getByRole('button', {name: 'Desconectar', exact: true}).click();
  await page.getByRole('heading', {name: 'Conectadas · ninguna', exact: true}).waitFor();
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: 'output/playwright/connections-09b-mobile-source-layout.png', fullPage: true});
  const width = await page.evaluate(() => document.documentElement.scrollWidth);
  if (errors.length) throw Error(errors.join('\n'));
  return {passed: true, originalHeading: reference, actualHeading: actual, executed: final.calls.filter(c => c.op === 'commit').length,
    mobile: {viewport: 390, documentWidth: width, note: 'Original fixed-width design, responsive variant needed'}, pageErrors: errors};
}
