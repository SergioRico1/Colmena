// Phosphor glyphs for Colmena (src/components/Icon.js): reads the glyphs the adapter names from
// @phosphor-icons/react (devDependency, pinned) and writes src/components/icons.gen.js with only
// the weights Colmena draws — "regular" and "fill" — as plain path data, so the bundle carries two
// weights of the glyphs in use instead of six of every one. Run after adding a name to Icon.js:
//   node scripts/gen-icons.mjs        (writes the file)
//   node scripts/gen-icons.mjs --check (exits 1 when the file is out of date)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const adapter = readFileSync(path.join(root, "src/components/Icon.js"), "utf8");
const defs = path.join(root, "node_modules/@phosphor-icons/react/dist/defs");
const WEIGHTS = ["regular", "fill"];

// Every `icon(G.Name, …)` in the adapter.
const names = [...new Set([...adapter.matchAll(/icon\(G\.(\w+)/g)].map((m) => m[1]))].sort();
if (!names.length) throw Error("No icon(G.Name) calls found in src/components/Icon.js");

/** The elements of one weight: [[tag, {attrs}], …], read from the defs module's createElement calls. */
function elementsOf(source, weight) {
  const start = source.indexOf(`"${weight}",`);
  if (start < 0) throw Error("weight " + weight + " missing");
  const end = source.indexOf("\n  ]", start);
  const chunk = source.slice(start, end);
  const out = [];
  for (const m of chunk.matchAll(/createElement\("(\w+)", (\{[^}]*\})\)/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/(\w+): ("[^"]*"|[\d.]+)/g)) attrs[a[1]] = a[2].startsWith('"') ? JSON.parse(a[2]) : Number(a[2]);
    out.push([m[1], attrs]);
  }
  if (!out.length) throw Error("no elements for " + weight);
  return out;
}

const glyphs = {};
for (const name of names) {
  const file = path.join(defs, name + ".es.js");
  if (!existsSync(file)) throw Error(`Phosphor has no glyph «${name}» (src/components/Icon.js)`);
  const source = readFileSync(file, "utf8");
  glyphs[name] = Object.fromEntries(WEIGHTS.map((w) => [w, elementsOf(source, w)]));
}
// Most glyphs are one <path>: store its d as a string; anything else as [tag, attrs] pairs.
const compact = (els) => (els.length === 1 && els[0][0] === "path" && Object.keys(els[0][1]).length === 1 ? els[0][1].d : els);
const body = names.map((n) => `export const ${n} = [${WEIGHTS.map((w) => JSON.stringify(compact(glyphs[n][w]))).join(", ")}];`).join("\n");
const version = JSON.parse(readFileSync(path.join(root, "node_modules/@phosphor-icons/react/package.json"), "utf8")).version;
const out = `// GENERATED by scripts/gen-icons.mjs from @phosphor-icons/react ${version}. Do not edit.
// Phosphor Icons, MIT License, Copyright (c) 2020 Phosphor Icons (https://phosphoricons.com).
// Each glyph: [regular, fill] on a 256 × 256 grid; a string is one path's d, else [tag, attrs] pairs.
// One export per glyph, so a bundle keeps only the glyphs it draws.
${body}
`;
const target = path.join(root, "src/components/icons.gen.js");
if (process.argv.includes("--check")) {
  const same = existsSync(target) && readFileSync(target, "utf8") === out;
  console.log(same ? "icons.gen.js is up to date" : "icons.gen.js is out of date: run node scripts/gen-icons.mjs");
  process.exit(same ? 0 : 1);
}
writeFileSync(target, out);
console.log(`${names.length} glyphs, ${WEIGHTS.join(" + ")}, ${Math.round(out.length / 1024)} KB → src/components/icons.gen.js`);
